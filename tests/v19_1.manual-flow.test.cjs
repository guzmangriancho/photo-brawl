const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const root = path.join(__dirname, '..');
const load = file => fs.readFileSync(path.join(root,file),'utf8');
const creator = load('src/components/FighterCreator.tsx');
const css = load('src/components/fighterCreator.css');
const sw = load('public/sw.js');
const guideEntry = creator.match(/\{title:'1 · CREA LA FICHA'.*?\},/s)?.[0] || '';
assert.ok(guideEntry, 'La primera ayuda se titula Crea la ficha');
assert.doesNotMatch(guideEntry, /pide el JSON completo/i, 'La ayuda no pide instrucciones adicionales');
assert.match(guideEntry,/adjunta tu foto original directamente en ese chat/i);
const manualStart = creator.indexOf("mode==='guided' ? <div className=\"pb-creator-columns pb-creator-manual-layout\"");
const manualEnd = creator.indexOf(' : <div className="pb-creator-columns pb-creator-photo-step pb-creator-auto-layout">',manualStart);
assert.ok(manualStart >= 0 && manualEnd > manualStart);
const manual = creator.slice(manualStart, manualEnd);
assert.match(manual,/showPrompt\('PHOTO'\)/);
assert.match(manual,/pasteAndValidate\(\)/);
assert.doesNotMatch(manual,/!photoFile/,'El modo manual no requiere foto subida');
assert.doesNotMatch(manual,/type="file"/,'El modo manual solo pide adjuntar foto en el chat externo');
const automatic = creator.slice(manualEnd,creator.indexOf("{step==='PHOTO' && showJson",manualEnd));
assert.match(automatic,/type="file"/);
assert.match(automatic,/disabled=\{!photoFile\|\|!key\.trim\(\)\|\|busy\}/);
assert.match(creator,/CREACIÓN GUIADA · 4 PASOS/);
assert.match(creator,/2 · ABRIR MI IA/);
assert.match(creator,/3 · PEGAR RESPUESTA/);
assert.match(creator,/navigator\.clipboard\?\.writeText/);
assert.match(css,/\.pb-creator-manual-layout\{/);
assert.match(css,/@media \(orientation:portrait\)/);
assert.match(sw,/pb-shell-v19-2-quick-clipboard/);
const parsed=ts.createSourceFile('FighterCreator.tsx',creator,ts.ScriptTarget.Latest,true,ts.ScriptKind.TSX);
assert.equal(parsed.parseDiagnostics.length,0,parsed.parseDiagnostics.map(d=>d.messageText).join('\n'));
console.log('OK: 13 comprobaciones de modo manual, ayuda, PWA y sintaxis TSX.');
